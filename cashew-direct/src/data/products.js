export function getRelatedProducts(product, limit = 4) {
  return products
    .filter((p) => p.id !== product.id && p.category === product.category)
    .slice(0, limit)
    .concat(
      products.filter((p) => p.id !== product.id && p.category !== product.category)
    )
    .slice(0, limit);
}

